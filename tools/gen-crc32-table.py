#!/usr/bin/env python3
"""Generate src/crc32_table.h: the 8 lookup tables for slicing-by-8 CRC-32.

    python3 tools/gen-crc32-table.py > src/crc32_table.h

CRC-32 as used by gzip, zlib and PNG: reflected polynomial 0xEDB88320.
TABLE[0][b] is the CRC of the single byte b; TABLE[k][b] advances
TABLE[k-1][b] by one more zero byte. The unit tests recompute every result
with a bit-at-a-time reference, so a wrong table cannot go unnoticed.
"""

POLY = 0xEDB88320

t0 = []
for b in range(256):
    c = b
    for _ in range(8):
        c = (c >> 1) ^ (POLY if c & 1 else 0)
    t0.append(c)

tables = [t0]
for k in range(1, 8):
    prev = tables[-1]
    tables.append([(prev[b] >> 8) ^ t0[prev[b] & 0xFF] for b in range(256)])

print("/* Generated by tools/gen-crc32-table.py. Do not edit. */")
print("/* clang-format off */")
print("static const uint32_t CRC32_TABLE[8][256] = {")
for t in tables:
    print("    {")
    for i in range(0, 256, 6):
        row = ", ".join(f"0x{v:08x}" for v in t[i:i + 6])
        print(f"        {row},")
    print("    },")
print("};")
print("/* clang-format on */")
